// Converts the stacked "KIDS / SALON" wordmark (Fraunces Black) into SVG path
// data, glyph by glyph, so the logo and the loading animation never depend on
// web-font loading and each letter can be tilted like the salon's sticker logo.
// Run: node scripts/build-wordmark.mjs
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const load = (w) => {
  const buf = readFileSync(`${root}node_modules/@fontsource/fraunces/files/fraunces-latin-${w}-normal.woff`);
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};
const font = load(900);
const SIZE = 100;
const r = (n) => +n.toFixed(2);

// Per-letter tilt (deg) and vertical nudge — the playful "jumping letters" of the real logo.
const jitter = {
  KIDS: [[-6, 2], [8, -6], [-4, 3], [6, -2]],
  SALON: [[5, -3], [-7, 4], [4, -5], [-5, 2], [7, -3]],
};

function line(text, y, tracking) {
  let x = 0;
  const glyphs = [];
  [...text].forEach((ch, i) => {
    const g = font.charToGlyph(ch);
    const p = g.getPath(x, y, SIZE);
    const bb = p.getBoundingBox();
    const [rot, dy] = jitter[text][i];
    glyphs.push({
      d: p.toPathData(1),
      cx: r((bb.x1 + bb.x2) / 2),
      cy: r((bb.y1 + bb.y2) / 2),
      rot,
      dy,
    });
    x += (g.advanceWidth / font.unitsPerEm) * SIZE + tracking;
  });
  return { glyphs, width: x - tracking };
}

const top = line('KIDS', 80, 2);
const bottom = line('SALON', 176, 0);
// centre each line within the wider one
const W = Math.max(top.width, bottom.width);
const shift = (l) => {
  const dx = (W - l.width) / 2;
  return l.glyphs.map((g) => ({ ...g, dx: r(dx), cx: r(g.cx + dx) }));
};

const glyphs = [...shift(top), ...shift(bottom)];
const pad = 18;
const out = `// AUTO-GENERATED by scripts/build-wordmark.mjs — do not edit by hand.
export interface Glyph { d: string; cx: number; cy: number; rot: number; dy: number; dx: number }
export const logo = {
  viewBox: '${-pad} ${-pad + 6} ${r(W + pad * 2)} ${186 + pad * 2 - 6}',
  glyphs: ${JSON.stringify(glyphs)} as Glyph[],
};
`;
writeFileSync(`${root}src/components/brand/paths.ts`, out);
console.log('logo width', r(W), 'glyphs', glyphs.length);
